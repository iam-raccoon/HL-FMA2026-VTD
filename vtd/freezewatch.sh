#!/usr/bin/env bash
# 주행이 얼어붙으면 그 판을 끊는다. 안 끊으면 1600초 타임아웃까지 태운다.
#
#   bash vtd/freezewatch.sh <run.csv> [정지로 볼 시간(초), 기본 150]
#
# 왜(2026-08-25 코스 G): t=41s 에 물려 **503초를 낭비**했다. 사람이 안 보고 있으면
# 스윕 한 판이 통째로 날아간다.
#
# ⚠️ **판정은 변위로 한다. 속도가 아니다.** 정체에서 차는 조금씩 꿈틀댄다 —
#    `drive.py` 의 동결 감시도 같은 이유로 순간속도 기준을 버렸다.
# ⚠️ 임계값이 0.5m 였는데 **너무 빡빡해서 놓쳤다**(실측 2026-08-26 코스 E:
#    150초에 **0.79m** 움직여 안 걸렸고 1600초 타임아웃까지 갔다 — 27분 낭비).
#    같은 판의 코스 A 는 정확히 0.00m 라 걸렸다. 실제로 가고 있으면 150초에
#    수백 m 를 간다. `drive.py::FROZEN_MOVE` 와 같은 **3m** 로 맞춘다.
# ⚠️ 창의 처음과 끝만 비교하면 나갔다 돌아온 경우를 놓친다. **최대 이탈거리**로 본다.
set -u
CSV="$1"
LIMIT="${2:-150}"
MOVE="${MOVE:-3.0}"          # 이 안에서만 움직였으면 '못 가고 있다'[m]
sleep 60                      # 출발 직후는 원래 느리다
while [ -s "$CSV" ]; do
  pgrep -f "main[.]py --host" >/dev/null || exit 0     # 주행이 끝났다
  # 25Hz 기준 3000행 ~ 120초. 넉넉히 4000행을 본다.
  read -r D T <<<"$(tail -n 4000 "$CSV" | awk -F, '
      NR==1 { x=$2; y=$3; t=$1; m=0 }
      { d=sqrt(($2-x)^2 + ($3-y)^2); if (d>m) m=d }
      END   { printf "%.2f %.0f", m, $1-t }')"
  if [ "${T:-0}" -ge "$LIMIT" ] && [ "$(echo "${D:-99} < $MOVE" | bc -l)" = "1" ]; then
      echo "[동결감지] ${T}초간 ${D}m -> 주행 중단"
      pkill -f "main[.]py --host"
      exit 1
  fi
  sleep 20
done
